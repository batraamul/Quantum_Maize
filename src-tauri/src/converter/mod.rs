//! DOCX ⇄ LaTeX conversion through Pandoc.
//!
//! Conversion is never lossless; every run produces a `ConversionReport`
//! listing what was converted, what Pandoc warned about and what needs manual
//! attention. Source files are only read: DOCX→LaTeX writes a *new* project,
//! LaTeX→DOCX writes a new .docx chosen by the user.

use crate::compiler::detect;
use crate::compiler::proc::{hidden_command, run_capture};
use crate::error::{AppError, AppResult};
use serde::Serialize;
use std::fs;
use std::path::{Path, PathBuf};
use std::time::Duration;

#[derive(Debug, Serialize, Default)]
#[serde(rename_all = "camelCase")]
pub struct ConversionReport {
    pub direction: String,
    pub output: String,
    pub pandoc_version: String,
    pub counts: Vec<(String, usize)>,
    pub warnings: Vec<String>,
    pub manual: Vec<String>,
    pub files: Vec<String>,
}

impl ConversionReport {
    pub fn markdown(&self) -> String {
        let mut s = format!("# Conversion report ({})\n\nGenerated by Quantum Maze using {}.\nOutput: `{}`\n\n## Converted content\n\n", self.direction, self.pandoc_version, self.output);
        for (k, v) in &self.counts {
            s.push_str(&format!("- {k}: {v}\n"));
        }
        s.push_str("\n## Needs manual attention\n\n");
        if self.manual.is_empty() {
            s.push_str("- Nothing specific detected. Still proof-read the result: conversion is never guaranteed to be lossless.\n");
        }
        for m in &self.manual {
            s.push_str(&format!("- {m}\n"));
        }
        s.push_str("\n## Pandoc warnings\n\n");
        if self.warnings.is_empty() {
            s.push_str("- None\n");
        }
        for w in &self.warnings {
            s.push_str(&format!("- {w}\n"));
        }
        s
    }
}

fn pandoc(tex_bin: Option<&str>) -> AppResult<PathBuf> {
    detect::find_tool("pandoc", tex_bin).ok_or_else(|| AppError::NotFound("Pandoc is required for Word conversion. Install it from https://pandoc.org/installing.html and rescan.".into()))
}

fn version(p: &Path) -> String {
    let mut c = hidden_command(p);
    c.arg("--version");
    run_capture(c, Duration::from_secs(10)).map(|o| o.stdout.lines().next().unwrap_or("pandoc").to_string()).unwrap_or_else(|_| "pandoc".into())
}

fn warnings_from(stderr: &str) -> Vec<String> {
    stderr.lines().filter(|l| l.contains("[WARNING]") || l.to_lowercase().contains("could not")).map(|l| l.replace("[WARNING] ", "").trim().to_string()).take(200).collect()
}

fn slug(s: &str) -> String {
    let mut o: String = s.to_lowercase().chars().map(|c| if c.is_ascii_alphanumeric() { c } else { '-' }).collect();
    while o.contains("--") {
        o = o.replace("--", "-");
    }
    let o = o.trim_matches('-').chars().take(40).collect::<String>();
    if o.is_empty() { "section".into() } else { o }
}

/// Split a LaTeX body into (preface, [(title, text)]) at \section commands.
pub fn split_sections(body: &str) -> (String, Vec<(String, String)>) {
    let re = regex::Regex::new(r"(?m)^\\section\*?\{").unwrap();
    let starts: Vec<usize> = re.find_iter(body).map(|m| m.start()).collect();
    if starts.is_empty() {
        return (body.to_string(), vec![]);
    }
    let pre = body[..starts[0]].to_string();
    let mut out = Vec::new();
    for (i, &s) in starts.iter().enumerate() {
        let e = starts.get(i + 1).copied().unwrap_or(body.len());
        let chunk = &body[s..e];
        let title = chunk.find('{').and_then(|o| {
            let mut depth = 0;
            for (k, ch) in chunk[o..].char_indices() {
                match ch {
                    '{' => depth += 1,
                    '}' => {
                        depth -= 1;
                        if depth == 0 {
                            return Some(chunk[o + 1..o + k].to_string());
                        }
                    }
                    _ => {}
                }
            }
            None
        });
        out.push((title.unwrap_or_else(|| format!("Section {}", i + 1)), chunk.to_string()));
    }
    (pre, out)
}

/// Replaces Greek letters and common symbols typed as plain Unicode with LaTeX commands
/// (`\ensuremath{..}` works in both text and math). Verbatim/listing environments are left
/// untouched. Returns the new text and the number of replacements.
pub fn texify_unicode(text: &str) -> (String, usize) {
    const MAP: &[(char, &str)] = &[
        ('α', "\\alpha"), ('β', "\\beta"), ('γ', "\\gamma"), ('δ', "\\delta"), ('ε', "\\varepsilon"), ('ζ', "\\zeta"),
        ('η', "\\eta"), ('θ', "\\theta"), ('ι', "\\iota"), ('κ', "\\kappa"), ('λ', "\\lambda"), ('μ', "\\mu"), ('µ', "\\mu"),
        ('ν', "\\nu"), ('ξ', "\\xi"), ('π', "\\pi"), ('ρ', "\\rho"), ('σ', "\\sigma"), ('τ', "\\tau"), ('υ', "\\upsilon"),
        ('φ', "\\varphi"), ('χ', "\\chi"), ('ψ', "\\psi"), ('ω', "\\omega"), ('Γ', "\\Gamma"), ('Δ', "\\Delta"),
        ('Θ', "\\Theta"), ('Λ', "\\Lambda"), ('Ξ', "\\Xi"), ('Π', "\\Pi"), ('Σ', "\\Sigma"), ('Φ', "\\Phi"), ('Ψ', "\\Psi"),
        ('Ω', "\\Omega"), ('×', "\\times"), ('±', "\\pm"), ('≤', "\\leq"), ('≥', "\\geq"), ('≠', "\\neq"), ('≈', "\\approx"),
        ('∞', "\\infty"), ('→', "\\rightarrow"), ('←', "\\leftarrow"), ('∑', "\\sum"), ('∫', "\\int"), ('√', "\\surd"),
        ('∂', "\\partial"), ('∈', "\\in"), ('°', "^{\\circ}"), ('·', "\\cdot"), ('÷', "\\div"), ('∝', "\\propto"),
    ];
    let mut out = String::with_capacity(text.len());
    let mut n = 0;
    let mut verbatim = false;
    for line in text.split_inclusive('\n') {
        let t = line.trim_start();
        if ["\\begin{verbatim}", "\\begin{Verbatim}", "\\begin{lstlisting}", "\\begin{Highlighting}"].iter().any(|p| t.starts_with(p)) {
            verbatim = true;
        }
        if verbatim {
            out.push_str(line);
            if ["\\end{verbatim}", "\\end{Verbatim}", "\\end{lstlisting}", "\\end{Highlighting}"].iter().any(|p| t.starts_with(p)) {
                verbatim = false;
            }
            continue;
        }
        for c in line.chars() {
            match MAP.iter().find(|(k, _)| *k == c) {
                Some((_, cmd)) => {
                    out.push_str("\\ensuremath{");
                    out.push_str(cmd);
                    out.push('}');
                    n += 1;
                }
                None => out.push(c),
            }
        }
    }
    (out, n)
}

/// DOCX → new structured LaTeX project at `dest` (must not exist or be empty).
pub fn docx_to_latex(docx: &Path, dest: &Path, tex_bin: Option<&str>) -> AppResult<ConversionReport> {
    let pd = pandoc(tex_bin)?;
    if !docx.is_file() {
        return Err(AppError::NotFound(docx.display().to_string()));
    }
    if dest.exists() && fs::read_dir(dest)?.next().is_some() {
        return Err(AppError::Invalid(format!("{} already exists and is not empty", dest.display())));
    }
    fs::create_dir_all(dest)?;
    let mut cmd = hidden_command(&pd);
    cmd.current_dir(dest).arg("--from=docx").arg("--to=latex").arg("--standalone").arg("--wrap=preserve").arg("--extract-media=.").arg("--verbose").arg(docx);
    let out = run_capture(cmd, Duration::from_secs(300))?;
    if out.code != Some(0) {
        return Err(AppError::Other(format!("Pandoc failed: {}", out.stderr.lines().last().unwrap_or("unknown error"))));
    }
    let doc = out.stdout;
    let (preamble, body) = match (doc.find("\\begin{document}"), doc.rfind("\\end{document}")) {
        (Some(a), Some(b)) if b > a => (doc[..a].to_string(), doc[a + "\\begin{document}".len()..b].to_string()),
        _ => return Err(AppError::Other("Pandoc produced no LaTeX document body".into())),
    };
    // Pandoc wraps headings as \hypertarget{id}{%\n\section{..}\label{..}}; unwrap
    // them so the body can be split into one file per section.
    let unwrap = regex::Regex::new(r"(?m)^\\hypertarget\{[^{}]*\}\{%\r?\n(\\(?:sub|subsub)?section\*?\{[^\n]*)\}[ \t]*$").unwrap();
    let body = unwrap.replace_all(&body, "$1").into_owned();
    // Word text often contains Greek letters and symbols as plain Unicode, which the default
    // LaTeX fonts silently drop. Turn them into LaTeX commands.
    let (body, texified) = texify_unicode(&body);
    let (pre, sections) = split_sections(&body);
    let mut inputs = String::new();
    let mut files = vec!["main.tex".to_string()];
    fs::create_dir_all(dest.join("sections"))?;
    for (i, (title, text)) in sections.iter().enumerate() {
        let name = format!("sections/{:02}-{}.tex", i + 1, slug(title));
        fs::write(dest.join(&name), text)?;
        inputs.push_str(&format!("\\input{{{}}}\n", name.trim_end_matches(".tex")));
        files.push(name);
    }
    let main = format!("% Converted from {} by Quantum Maze (Pandoc). See CONVERSION_REPORT.md.\n{}\\begin{{document}}\n{}\n{}\\end{{document}}\n", docx.file_name().unwrap_or_default().to_string_lossy(), preamble, pre.trim(), inputs);
    fs::write(dest.join("main.tex"), main)?;
    let all = format!("{pre}{}", sections.iter().map(|s| s.1.as_str()).collect::<String>());
    let media: Vec<String> = walkdir::WalkDir::new(dest.join("media")).into_iter().filter_map(|e| e.ok()).filter(|e| e.file_type().is_file()).map(|e| e.path().strip_prefix(dest).unwrap().to_string_lossy().replace('\\', "/")).collect();
    let mut manual = Vec::new();
    for m in &media {
        let l = m.to_lowercase();
        if l.ends_with(".emf") || l.ends_with(".wmf") {
            manual.push(format!("{m}: EMF/WMF images cannot be used by LaTeX — export them as PDF or PNG and update the \\includegraphics path."));
        }
    }
    if all.contains("ADDIN ZOTERO") || all.contains("ADDIN EN.CITE") || all.contains("CSL_CITATION") {
        manual.push("Reference-manager citations (Zotero/EndNote fields) were converted as plain text. Re-insert them as \\cite{} with a .bib file.".into());
    }
    if !all.contains("\\cite") {
        manual.push("No citation commands were produced: references from Word are plain text. Create a .bib file and replace in-text citations with \\cite{}.".into());
    }
    if texified > 0 {
        manual.push(format!("{texified} Greek letter(s)/symbol(s) typed as plain characters in Word were rewritten as LaTeX commands (e.g. λ → \\ensuremath{{\\lambda}}). Check they read correctly."));
    }
    manual.push("Pandoc's preamble was kept for compatibility. To use a journal format, copy the sections into a project created from the Journal Library.".into());
    files.extend(media.iter().cloned());
    let mut r = ConversionReport {
        direction: "DOCX → LaTeX".into(),
        output: dest.display().to_string(),
        pandoc_version: version(&pd),
        counts: vec![
            ("Sections".into(), sections.len()),
            ("Subsections".into(), all.matches("\\subsection{").count()),
            ("Tables".into(), all.matches("\\begin{longtable}").count() + all.matches("\\begin{tabular}").count()),
            ("Images".into(), media.len()),
            ("Display equations".into(), all.matches("\\[").count() + all.matches("\\begin{equation").count()),
            ("Inline maths".into(), all.matches("\\(").count()),
            ("Footnotes".into(), all.matches("\\footnote{").count()),
            ("Hyperlinks".into(), all.matches("\\href{").count()),
        ],
        warnings: warnings_from(&out.stderr),
        manual,
        files,
    };
    r.files.push("CONVERSION_REPORT.md".into());
    fs::write(dest.join("CONVERSION_REPORT.md"), r.markdown())?;
    Ok(r)
}

/// LaTeX project → DOCX at `dest_docx`.
pub fn latex_to_docx(root: &Path, main: &str, dest_docx: &Path, tex_bin: Option<&str>) -> AppResult<ConversionReport> {
    let pd = pandoc(tex_bin)?;
    let main_abs = crate::security::resolve_in_root(root, main)?;
    let mut all = String::new();
    let mut bibs = Vec::new();
    for e in walkdir::WalkDir::new(root).max_depth(6).into_iter().filter_map(|e| e.ok()).filter(|e| e.file_type().is_file()) {
        let p = e.path();
        let rel = p.strip_prefix(root).unwrap().to_string_lossy().replace('\\', "/");
        if rel.starts_with(".qmaze") || rel.starts_with("output/") {
            continue;
        }
        match p.extension().and_then(|x| x.to_str()) {
            Some("tex") => all.push_str(&fs::read_to_string(p).unwrap_or_default()),
            Some("bib") => bibs.push(rel),
            _ => {}
        }
    }
    let mut cmd = hidden_command(&pd);
    cmd.current_dir(root).arg("--from=latex").arg("--to=docx").arg("--verbose").arg(format!("--resource-path=.{}figures{}images", if cfg!(windows) { ";" } else { ":" }, if cfg!(windows) { ";" } else { ":" }));
    if !bibs.is_empty() {
        cmd.arg("--citeproc");
        for b in &bibs {
            cmd.arg(format!("--bibliography={b}"));
        }
    }
    cmd.arg("-o").arg(dest_docx).arg(&main_abs);
    let out = run_capture(cmd, Duration::from_secs(300))?;
    if out.code != Some(0) || !dest_docx.exists() {
        return Err(AppError::Other(format!("Pandoc failed: {}", out.stderr.lines().last().unwrap_or("unknown error"))));
    }
    let clean: String = all.lines().map(|l| l.split('%').next().unwrap_or("")).collect::<Vec<_>>().join("\n");
    let mut manual = Vec::new();
    let checks = [
        ("\\begin{tikzpicture}", "TikZ drawings are not converted. Export them as images (e.g. with the standalone class) and include the images."),
        ("\\begin{algorithm", "Algorithm/pseudocode environments are converted as plain text at best — check their layout."),
        ("\\newcommand", "Custom macros (\\newcommand) are expanded only when Pandoc understands them; check symbols and notation."),
        ("\\begin{subfigure}", "Sub-figures become separate images; captions/labels may need adjusting."),
        ("\\multirow", "Merged table cells (\\multirow) are not preserved."),
        ("\\begin{lstlisting}", "Code listings lose syntax highlighting."),
        ("\\SI{", "siunitx quantities (\\SI) may not convert; check units."),
        ("\\cref", "cleveref references (\\cref) may convert as plain keys."),
    ];
    for (needle, msg) in checks {
        if clean.contains(needle) {
            manual.push(msg.to_string());
        }
    }
    if let Some(c) = regex::Regex::new(r"\\documentclass\s*(?:\[[^\]]*\])?\s*\{([^}]+)\}").unwrap().captures(&clean) {
        let cls = c[1].to_string();
        if !["article", "report", "book", "amsart"].contains(&cls.as_str()) {
            manual.push(format!("Publisher class `{cls}`: its layout and special commands (author blocks, keywords environments) are not reproduced in Word."));
        }
    }
    if ["$", "\\[", "\\(", "\\begin{equation", "\\begin{align", "\\begin{multline", "\\begin{gather"].iter().any(|n| clean.contains(n)) {
        manual.push("Equations are converted to native Word equations; check complex alignments and numbering.".into());
    }
    manual.push("Page layout (columns, margins, floats placement) follows Word defaults, not the LaTeX class — apply the journal's Word template if it has one.".into());
    Ok(ConversionReport {
        direction: "LaTeX → DOCX".into(),
        output: dest_docx.display().to_string(),
        pandoc_version: version(&pd),
        counts: vec![
            ("Sections".into(), clean.matches("\\section").count()),
            ("Figures".into(), clean.matches("\\begin{figure").count()),
            ("Tables".into(), clean.matches("\\begin{table").count()),
            ("Equations".into(), clean.matches("\\begin{equation").count() + clean.matches("\\begin{align").count()),
            ("Citations".into(), clean.matches("\\cite").count()),
            ("Bibliography files".into(), bibs.len()),
        ],
        warnings: warnings_from(&out.stderr),
        manual,
        files: vec![dest_docx.display().to_string()],
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn unicode_symbols_become_latex_outside_verbatim() {
        let (t, n) = texify_unicode("Spacing λ/2 at 45° ± 1\n\\begin{verbatim}\nλ stays\n\\end{verbatim}\nplain é text\n");
        assert_eq!(n, 3);
        assert!(t.contains("\\ensuremath{\\lambda}/2"));
        assert!(t.contains("45\\ensuremath{^{\\circ}}"));
        assert!(t.contains("λ stays"));
        assert!(t.contains("plain é text"));
    }
    #[test]
    fn splits_sections() {
        let (pre, s) = split_sections("intro text\n\\section{A {b}}\nx\n\\section*{C}\ny\n");
        assert_eq!(pre, "intro text\n");
        assert_eq!(s.len(), 2);
        assert_eq!(s[0].0, "A {b}");
        assert_eq!(s[1].0, "C");
        assert_eq!(slug("Results & Discussion!"), "results-discussion");
        let re = regex::Regex::new(r"(?m)^\\hypertarget\{[^{}]*\}\{%\r?\n(\\(?:sub|subsub)?section\*?\{[^\n]*)\}[ \t]*$").unwrap();
        let src = "\\hypertarget{intro}{%\n\\section{Intro {x}}\\label{intro}}\n";
        assert_eq!(re.replace_all(src, "$1"), "\\section{Intro {x}}\\label{intro}\n");
    }
}
