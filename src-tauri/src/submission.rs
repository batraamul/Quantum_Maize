//! Submission package: sources, figures, bibliography (.bib and generated
//! .bbl), required class/style files and the final PDF, plus a MANIFEST with
//! sizes and SHA-256 checksums.

use crate::error::{AppError, AppResult};
use crate::filesystem::{file_kind, META_DIR};
use serde::Serialize;
use sha2::{Digest, Sha256};
use std::io::Write;
use std::path::Path;

#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct ManifestEntry {
    pub path: String,
    pub size: u64,
    pub sha256: String,
    pub role: String,
}

fn role(rel: &str) -> &'static str {
    match file_kind(rel) {
        "tex" => "source",
        "bib" => "bibliography",
        "style" => "class/style",
        "image" => "figure",
        "pdf" if rel.starts_with("figures/") || rel.contains("/figures/") => "figure",
        "pdf" => "document",
        _ => "supplementary",
    }
}

pub fn build(root: &Path, main_file: &str, journal: Option<&str>, dest: &Path) -> AppResult<Vec<ManifestEntry>> {
    let root = root.canonicalize()?;
    let stem = Path::new(main_file).file_stem().unwrap_or_default().to_string_lossy().into_owned();
    let pdf = root.join(META_DIR).join("build").join(format!("{stem}.pdf"));
    if !pdf.exists() {
        return Err(AppError::NotFound("no successful build — compile the document before packaging".into()));
    }
    let mut items: Vec<(String, std::path::PathBuf)> = Vec::new();
    for e in walkdir::WalkDir::new(&root)
        .into_iter()
        .filter_entry(|e| {
            let n = e.file_name().to_string_lossy();
            !(e.depth() == 1 && (n == "output" || n == META_DIR)) && n != ".git" && n != "__MACOSX"
        })
        .filter_map(|e| e.ok())
        .filter(|e| e.file_type().is_file())
    {
        let rel = e.path().strip_prefix(&root).unwrap().to_string_lossy().replace('\\', "/");
        if file_kind(&rel) == "build" || rel.contains(".pf-tmp-") || rel.ends_with("CONVERSION_REPORT.md") {
            continue;
        }
        if Some(e.path().to_path_buf()) == dest.canonicalize().ok() {
            continue;
        }
        items.push((rel, e.path().to_path_buf()));
    }
    let bbl = root.join("output").join(format!("{stem}.bbl"));
    if bbl.exists() {
        // Many publishers require the generated .bbl next to the main file.
        let main_dir = Path::new(main_file).parent().map(|p| p.to_string_lossy().replace('\\', "/")).unwrap_or_default();
        let rel = if main_dir.is_empty() { format!("{stem}.bbl") } else { format!("{main_dir}/{stem}.bbl") };
        items.push((rel, bbl));
    }
    items.push((format!("{stem}.pdf"), pdf));
    let f = std::fs::File::create(dest)?;
    let mut z = zip::ZipWriter::new(f);
    let opts = zip::write::SimpleFileOptions::default().compression_method(zip::CompressionMethod::Deflated);
    let mut manifest = Vec::new();
    for (rel, p) in &items {
        let bytes = std::fs::read(p)?;
        let sha = format!("{:x}", Sha256::digest(&bytes));
        z.start_file(rel.as_str(), opts)?;
        z.write_all(&bytes)?;
        manifest.push(ManifestEntry { path: rel.clone(), size: bytes.len() as u64, sha256: sha, role: if rel.ends_with(".bbl") { "bibliography (generated)".into() } else if rel == &format!("{stem}.pdf") { "final PDF".into() } else { role(rel).into() } });
    }
    let mut txt = format!("Submission package generated by Quantum Maze {}\nCreated: {}\nMain file: {main_file}\nTarget: {}\n\n", env!("CARGO_PKG_VERSION"), chrono::Local::now().to_rfc3339(), journal.unwrap_or("not specified"));
    txt.push_str(&format!("{:<60} {:>10}  {:<24} {}\n", "File", "Bytes", "Role", "SHA-256"));
    for m in &manifest {
        txt.push_str(&format!("{:<60} {:>10}  {:<24} {}\n", m.path, m.size, m.role, m.sha256));
    }
    z.start_file("MANIFEST.txt", opts)?;
    z.write_all(txt.as_bytes())?;
    z.finish()?;
    Ok(manifest)
}
