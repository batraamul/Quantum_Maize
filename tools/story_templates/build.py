#!/usr/bin/env python3
"""Builds the bundled interactive-story templates.

    python3 tools/story_templates/build.py

Writes src-tauri/assets/story-templates/<id>/{template.json,story.json,assets/*.svg}.
To add a template: add a topic to one of the content_*.py files (or a layout to
formats.py) and run this script again. All artwork is generated by art.py.
"""
import json
import pathlib
import shutil
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import art  # noqa: E402
from content_a import TOPICS as A  # noqa: E402
from content_b import TOPICS as B  # noqa: E402
from content_c import TOPICS as C  # noqa: E402
from content_d import TOPICS as D  # noqa: E402
from formats import FORMATS  # noqa: E402

OUT = HERE.parents[1] / "src-tauri" / "assets" / "story-templates"
ADAPT = ("**Using this template.** Every block is editable: change the text in the panel on the right, "
         "replace the generated artwork with your own photographs, diagrams, GIFs or videos, and delete or "
         "reorder sections freely. Check figures against a current source before you publish.")


def blocks_for(t, files):
    seed = sum(ord(c) for c in t["id"])
    pal, mot = t["pal"], t["motifs"]
    files["assets/hero.svg"] = art.hero(pal, mot[0], seed)
    for i, (label, _) in enumerate(t["steps"]):
        files[f"assets/step-{i + 1}.svg"] = art.panel(pal, mot[(i + 1) % len(mot)], seed + 10 + i, i + 1, label)
    dia, pts = art.diagram(pal, [p[0] for p in t["parts"]], seed + 30, t["diag_title"])
    files["assets/diagram.svg"] = dia
    files["assets/before.svg"] = art.compare(pal, t["cmp"], seed + 40, False)
    files["assets/after.svg"] = art.compare(pal, t["cmp"], seed + 40, True)
    for i in range(3):
        files[f"assets/gallery-{i + 1}.svg"] = art.hero(pal, mot[i % len(mot)], seed + 50 + i, 1600, 1000)
    files["assets/section.svg"] = art.hero(pal, mot[-1], seed + 60, 1600, 700)

    b = [
        dict(type="hero", kicker=t["kicker"], title=t["title"], subtitle=t["sub"], image="assets/hero.svg", effect="kenburns", overlay=0.5, align="center"),
        dict(type="text", heading="", text=t["intro"], dropcap=True),
        dict(type="stats", items=[dict(value=v, prefix=p, suffix=s, label=l, plain=l.startswith("Year") or (not s and 1000 <= v <= 2100 and float(v).is_integer() and "port" in l)) for v, p, s, l in t["stats"]]),
        dict(type="divider", style="wave"),
        dict(type="text", heading=t["how"][0], text=t["how"][1], dropcap=False),
        dict(type="scrolly", side="right", steps=[dict(image=f"assets/step-{i + 1}.svg", text=f"**{lab}.** {txt}") for i, (lab, txt) in enumerate(t["steps"])]),
        dict(type="hotspots", image="assets/diagram.svg", caption="Tap the markers to explore each stage.",
             points=[dict(x=x, y=y, title=n, text=d) for (x, y), (n, d) in zip(pts, t["parts"])]),
        dict(type="text", heading=t["deep"][0], text=t["deep"][1], dropcap=False),
        dict(type="cards", flip=True, items=[dict(icon=e, title=n, text=d, image="") for e, n, d in t["concepts"]]),
        dict(type="image", src="assets/section.svg", caption="Replace with your own photograph or figure.", credit="", width="wide", effect="zoom-in"),
        dict(type="timeline", items=[dict(date=d, title=n, text=x, image="") for d, n, x in t["timeline"]]),
        dict(type="chart", title=t["chart"][0], labels=t["chart"][1], values=t["chart"][2], unit=t["chart"][3]),
        dict(type="compare", before="assets/before.svg", after="assets/after.svg", beforeLabel=t["compare"][0], afterLabel=t["compare"][1], caption=t["compare"][2]),
        dict(type="quote", text=t["idea"], by="Key idea"),
        dict(type="gallery", mode="carousel", images=[dict(src=f"assets/gallery-{i + 1}.svg", caption=c) for i, c in enumerate(t["gallery"])]),
        dict(type="text", heading=t["chal"][0], text=t["chal"][1], dropcap=False),
        dict(type="cards", flip=False, items=[dict(icon=e, title=n, text=d, image="") for e, n, d in t["apps"]]),
    ]
    for q, opts, ans, expl in t["quiz"]:
        b.append(dict(type="quiz", question=q, options=opts, answer=ans, explanation=expl))
    b.append(dict(type="text", heading="Key terms and next steps", text=t["more"] + "\n\n" + ADAPT, dropcap=False))
    return b


def blocks_for_format(f, files):
    seed = sum(ord(c) for c in f["id"])
    pal, mot = f["pal"], f["motifs"]
    ctx = {}
    files["assets/hero.svg"] = art.hero(pal, mot[0], seed)
    for i in range(4):
        files[f"assets/photo-{i + 1}.svg"] = art.hero(pal, mot[i % len(mot)], seed + 5 + i, 1600, 1000)
    files["assets/before.svg"] = art.compare(pal, f.get("cmp", "blur"), seed + 40, False)
    files["assets/after.svg"] = art.compare(pal, f.get("cmp", "blur"), seed + 40, True)
    if "map" in f:
        svg, pts = art.place_map(pal, f["map"], seed + 20)
    else:
        svg, pts = art.diagram(pal, f["parts"], seed + 20, f.get("diag_title", ""))
    files["assets/diagram.svg"] = svg
    ctx["pts"] = pts
    for i, label in enumerate(f.get("steps", [])):
        files[f"assets/step-{i + 1}.svg"] = art.panel(pal, mot[(i + 1) % len(mot)], seed + 10 + i, i + 1, label)
    return f["build"](ctx)


def write(t, blocks, files, category):
    d = OUT / t["id"]
    (d / "assets").mkdir(parents=True)
    for i, blk in enumerate(blocks):
        blk["id"] = f"t{i + 1:02d}"
    story = dict(version=1,
                 meta=dict(title=t["title"], subtitle=t["sub"], author="", date="", description=t["desc"]),
                 theme=dict(preset=t["preset"], accent="", font=t.get("font", "sans"), animation=t.get("anim", "fade-up"), progressBar=True, navDots=True),
                 blocks=blocks)
    (d / "story.json").write_text(json.dumps(story, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    used = set()

    def visit(v, key=""):
        if isinstance(v, str):
            if key in ("image", "src", "before", "after") and v:
                used.add(v)
        elif isinstance(v, list):
            for x in v:
                visit(x, key)
        elif isinstance(v, dict):
            for k, x in v.items():
                visit(x, k)

    visit(blocks)
    missing = used - set(files)
    assert not missing, f"{t['id']}: missing artwork {missing}"
    for p, svg in files.items():
        if p in used:  # ship only the artwork the story refers to
            (d / p).write_text(svg, encoding="utf-8")
    info = dict(id=t["id"], title=t["title"], category=category, description=t["desc"], sections=len(blocks), preset=t["preset"], cover="assets/hero.svg")
    (d / "template.json").write_text(json.dumps(info, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    return info


def main():
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)
    index = []
    for f in FORMATS:
        files = {}
        index.append(write(f, blocks_for_format(f, files), files, "Story formats"))
    for t in A + B + C + D:
        files = {}
        index.append(write(t, blocks_for(t, files), files, t["cat"]))
    ids = [i["id"] for i in index]
    assert len(ids) == len(set(ids)), "duplicate template id"
    size = sum(p.stat().st_size for p in OUT.rglob("*") if p.is_file())
    print(f"{len(index)} templates, {size / 1e6:.2f} MB")
    for i in index:
        print(f"  {i['category']:<28} {i['id']:<24} {i['sections']:>2} sections")


if __name__ == "__main__":
    main()
